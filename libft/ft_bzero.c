#include "libft.h"

void	ft_bzero(void *s, size_t n)
{
	size_t			i;
	unsigned char	*edit_s;

	i = 0;
	edit_s = s;
	while (i < n)
	{
		edit_s[i] = '\0';
		i++;
	}
}
