int	ft_str_is_alnum(char *str)
{
	while (*str != '\0')
	{
		if ((*str >= 'a' && *str <= 'z') || (*str >= 'A' && *str <= 'Z')
				|| (*str >= '0' && *str <= '9'))
			str++;
		else
			return (0);
	}
	return (1);
}
