#include "libft.h"

char	*ft_strjoin(char const *s1, char const *s2)
{
	char		*str;
	size_t		i;

	str = malloc(sizeof(char) * (ft_strlen(s1) + ft_strlen(s2)));
	i = 0;
	while (i < ft_strlen(s1))
	{
		str[i] = s1[i];
		i++;
	}
	while (i < ft_strlen(s1) + ft_strlen(s2))
	{
		str[i] = *s2;
		s2++;
		i++;
	}
	return (str);
}
